import { describe, expect, it } from "vitest";
import { isAutoGeneratedCategorySku, newProductSku, resolveProductSkuForSave } from "@/lib/admin/product-sku";

describe("newProductSku", () => {
  it("incrémente à partir des SKU existants de la catégorie", () => {
    expect(newProductSku("T-shirts", ["DGRY-TS-01", "DGRY-TS-03", "DGRY-HD-99"])).toBe("DGRY-TS-04");
  });

  it("évite un doublon exact", () => {
    expect(newProductSku("Hoodies", ["DGRY-HD-02"])).toBe("DGRY-HD-03");
  });
});

describe("resolveProductSkuForSave", () => {
  it("conserve un SKU manuel", () => {
    expect(resolveProductSkuForSave("T-shirts", "ma-ref-perso", [])).toBe("MA-REF-PERSO");
  });

  it("génère si vide", () => {
    expect(resolveProductSkuForSave("Jerseys", "  ", ["DGRY-JE-01"])).toBe("DGRY-JE-02");
  });
});

describe("isAutoGeneratedCategorySku", () => {
  it("reconnaît le motif DGRY", () => {
    expect(isAutoGeneratedCategorySku("DGRY-TS-12", "T-shirts")).toBe(true);
    expect(isAutoGeneratedCategorySku("CUSTOM-01", "T-shirts")).toBe(false);
  });
});
