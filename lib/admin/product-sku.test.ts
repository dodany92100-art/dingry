import { describe, expect, it } from "vitest";
import {
  isAutoGeneratedCategorySku,
  newProductSku,
  resolveProductSkuForSave,
  shouldRegenerateProductSku,
} from "@/lib/admin/product-sku";

describe("newProductSku", () => {
  it("alloue DIN-TSH-* en ignorant les SKU legacy DGRY", () => {
    expect(newProductSku("T-shirts", ["DGRY-TS-01", "DGRY-TS-03", "DGRY-HD-99"])).toBe("DIN-TSH-AAA");
  });

  it("incrémente le code modèle pour la même marque et type", () => {
    expect(newProductSku("Hoodies", ["DIN-HOO-AAB"])).toBe("DIN-HOO-AAC");
  });
});

describe("resolveProductSkuForSave", () => {
  it("conserve un SKU manuel (casse saisie)", () => {
    expect(resolveProductSkuForSave("T-shirts", "ma-ref-perso", [])).toBe("ma-ref-perso");
  });

  it("génère si vide", () => {
    expect(resolveProductSkuForSave("Jerseys", "  ", ["DIN-JER-AAB"])).toBe("DIN-JER-AAC");
  });

  it("incrémente une réf. auto en doublon (nouvelle fiche)", () => {
    expect(resolveProductSkuForSave("Hoodies", "DIN-HOO-AAB", ["DIN-HOO-AAB", "DIN-HOO-AAC"])).toBe(
      "DIN-HOO-AAD",
    );
  });

  it("conserve la réf. auto du produit édité", () => {
    expect(
      resolveProductSkuForSave("Hoodies", "DIN-HOO-AAC", ["DIN-HOO-AAB", "DIN-HOO-AAC"], {
        excludeNormalizedSku: "DIN-HOO-AAC",
      }),
    ).toBe("DIN-HOO-AAC");
  });
});

describe("shouldRegenerateProductSku", () => {
  it("réf. FYM obsolète quand la marque passe RTS", () => {
    expect(
      shouldRegenerateProductSku("FYM-CRW-AAA", "T-shirts", {
        brand: "ROCK THE STREET",
        collection: "Signature",
      }),
    ).toBe(true);
    expect(
      newProductSku("T-shirts", [], {
        brand: "ROCK THE STREET",
        collection: "Signature",
      }),
    ).toBe("RTS-TSH-AAA");
  });
});

describe("isAutoGeneratedCategorySku", () => {
  it("reconnaît le legacy DGRY et le nouveau DIN-TSH", () => {
    expect(isAutoGeneratedCategorySku("DGRY-TS-12", "T-shirts")).toBe(true);
    expect(isAutoGeneratedCategorySku("DIN-TSH-AAB", "T-shirts")).toBe(true);
    expect(isAutoGeneratedCategorySku("CUSTOM-01", "T-shirts")).toBe(false);
  });
});