import {
  DEFAULT_PRODUCT_BRAND,
  DEFAULT_PRODUCT_COLLECTION,
  type Brand,
  type ProductCategory,
  type ProductCollection,
} from "@/lib/admin/types";
import {
  brandToSkuMarqueCode,
  categoryToSkuTypeCode,
  isValidModelRef,
  isValidSku,
  newProductModelRef,
  normalizeSkuStrict,
  parseModelRef,
} from "@/lib/sku";

/** Saisie SKU CRM — conserve la casse, sans espaces (32 car. max). */
export function sanitizeSkuFieldInput(raw: string): string {
  return raw.replace(/\s+/g, "").slice(0, 32);
}

export function normalizeSkuInput(raw: string): string {
  return raw.toUpperCase().replace(/\s+/g, "").slice(0, 32);
}

const LEGACY_AUTO_SKU = /^DGRY-[A-Z]{2}-\d{2,}$/;

export type ProductSkuContext = {
  brand?: Brand;
  collection?: ProductCollection;
  productName?: string;
};

/**
 * `ref:` — référence technique (SKU / réf. modèle) vs nom produit.
 * Accepte l’ancien `DGRY-TS-01`, la réf. modèle `DIN-HOO-ESS` ou un SKU complet `FYM-TSH-BOU-NOI-L`.
 */
export function isLikelySkuReference(value: string): boolean {
  const raw = value.trim();
  if (!raw || /\s/.test(raw)) return false;
  if (isValidModelRef(raw) || isValidSku(raw)) return true;
  const norm = normalizeSkuInput(raw);
  if (LEGACY_AUTO_SKU.test(norm)) return true;
  if (/^DINGRY-[A-Z]{2,}-\d{2,}$/.test(norm)) return true;
  if (/-/.test(norm) && !/[a-z]/.test(raw)) return true;
  return false;
}

/** Réf. modèle auto générée par le CRM pour la marque + catégorie courantes. */
export function isAutoGeneratedModelRef(
  sku: string,
  category: ProductCategory,
  ctx?: ProductSkuContext,
): boolean {
  if (LEGACY_AUTO_SKU.test(normalizeSkuInput(sku))) return true;
  const marque = brandToSkuMarqueCode(ctx?.brand ?? DEFAULT_PRODUCT_BRAND, ctx?.collection ?? DEFAULT_PRODUCT_COLLECTION);
  const type = categoryToSkuTypeCode(category);
  if (!marque || !type) return false;
  const parsed = parseModelRef(sku);
  if (!parsed) return false;
  return parsed.marque === marque && parsed.type === type;
}

/** @deprecated Nom historique — utilise `isAutoGeneratedModelRef`. */
export function isAutoGeneratedCategorySku(
  sku: string,
  category: ProductCategory,
  ctx?: ProductSkuContext,
): boolean {
  return isAutoGeneratedModelRef(sku, category, ctx);
}

/**
 * Nouvelle fiche : régénérer si vide, auto (catégorie / contexte précédent / legacy) ou réf. obsolète (ex. FYM → RTS).
 */
export function shouldRegenerateProductSku(
  sku: string,
  category: ProductCategory,
  ctx?: ProductSkuContext,
  prev?: { category: ProductCategory; ctx?: ProductSkuContext },
): boolean {
  const trimmed = sku.trim();
  if (!trimmed) return true;
  if (LEGACY_AUTO_SKU.test(normalizeSkuInput(trimmed))) return true;
  const current = ctx ?? {};
  if (isAutoGeneratedModelRef(trimmed, category, current)) return true;
  if (prev && isAutoGeneratedModelRef(trimmed, prev.category, prev.ctx ?? current)) return true;
  const parsed = parseModelRef(trimmed);
  if (!parsed) return false;
  const marque = brandToSkuMarqueCode(
    current.brand ?? DEFAULT_PRODUCT_BRAND,
    current.collection ?? DEFAULT_PRODUCT_COLLECTION,
  );
  const type = categoryToSkuTypeCode(category);
  if (!marque || !type) return false;
  return parsed.marque !== marque || parsed.type !== type;
}

/**
 * Prochaine réf. modèle CRM : `MARQUE-TYPE-MODELE` (ex. `DIN-HOO-ABC`, `FYM-TSH-BOU`).
 * Le champ fiche = réf. modèle ; les variantes couleur portent le SKU complet 5 blocs.
 */
export function newProductSku(
  category: ProductCategory,
  existingSkus: readonly string[],
  ctx?: ProductSkuContext,
): string {
  return newProductModelRef({
    category,
    existingSkus,
    brand: ctx?.brand,
    collection: ctx?.collection,
    productName: ctx?.productName,
  });
}

export function resolveProductSkuForSave(
  category: ProductCategory,
  skuInput: string,
  existingSkus: readonly string[],
  options?: ProductSkuContext & { excludeNormalizedSku?: string },
): string {
  const ctx: ProductSkuContext = {
    brand: options?.brand,
    collection: options?.collection,
    productName: options?.productName,
  };
  const trimmed = skuInput.trim();
  const manual = trimmed ? sanitizeSkuFieldInput(trimmed) : "";
  const base = manual
    ? isAutoGeneratedModelRef(manual, category, ctx)
      ? normalizeSkuStrict(manual)
      : manual
    : newProductSku(category, existingSkus, ctx);
  const exclude = options?.excludeNormalizedSku ? normalizeSkuStrict(options.excludeNormalizedSku) : "";
  const used = new Set(
    existingSkus.map(normalizeSkuStrict).filter((sku) => sku.length > 0 && sku !== exclude),
  );
  if (isAutoGeneratedModelRef(base, category, ctx) && used.has(base)) {
    return newProductSku(category, existingSkus, ctx);
  }
  return base;
}