import type { ProductCategory } from "@/lib/admin/types";

const SKU_CATEGORY_TOKEN: Record<ProductCategory, string> = {
  Hoodies: "HD",
  "Hoodies zippés": "HZ",
  Crewnecks: "CR",
  "T-shirts": "TS",
  Jerseys: "JE",
  Pants: "PT",
  "Crop tops": "CT",
  Caps: "CP",
};

/** Saisie SKU CRM — conserve la casse, sans espaces (32 car. max). */
export function sanitizeSkuFieldInput(raw: string): string {
  return raw.replace(/\s+/g, "").slice(0, 32);
}

export function normalizeSkuInput(raw: string): string {
  return raw.toUpperCase().replace(/\s+/g, "").slice(0, 32);
}

/**
 * `ref:` — référence technique (SKU) vs nom produit.
 * Espaces / libellé marketing → nom ; `DGRY-PT-01`, codes sans espace → SKU.
 */
export function isLikelySkuReference(value: string): boolean {
  const raw = value.trim();
  if (!raw || /\s/.test(raw)) return false;
  const norm = normalizeSkuInput(raw);
  if (/^DGRY-[A-Z]{2}-\d{2,}$/.test(norm)) return true;
  if (/^DINGRY-[A-Z]{2,}-\d{2,}$/.test(norm)) return true;
  if (/^DINGRY-[A-Z0-9]+-\d{2,}$/.test(norm)) return true;
  if (/^[A-Z]{2,12}-\d{2,}$/.test(norm)) return true;
  if (/-/.test(norm) && /\d/.test(norm) && !/[a-z]/.test(raw)) return true;
  return false;
}

export function categorySkuToken(category: ProductCategory): string {
  return SKU_CATEGORY_TOKEN[category] ?? "XX";
}

/** Vrai si le SKU correspond au schéma auto `DGRY-{token}-##` pour la catégorie courante. */
export function isAutoGeneratedCategorySku(sku: string, category: ProductCategory): boolean {
  const token = categorySkuToken(category);
  return new RegExp(`^DGRY-${token}-\\d{2,}$`).test(normalizeSkuInput(sku));
}

/**
 * Prochain SKU unique par catégorie : `DGRY-TS-01`, `DGRY-HD-02`, etc.
 * S'appuie sur `existingSkus` pour l'incrément et l'anti-doublon.
 */
export function newProductSku(category: ProductCategory, existingSkus: readonly string[]): string {
  const token = categorySkuToken(category);
  const re = new RegExp(`^DGRY-${token}-(\\d+)$`);
  let max = 0;
  const used = new Set<string>();
  for (const raw of existingSkus) {
    const s = normalizeSkuInput(raw);
    if (!s) continue;
    used.add(s);
    const m = re.exec(s);
    if (m?.[1]) max = Math.max(max, parseInt(m[1], 10));
  }
  let n = max + 1;
  while (n < 10_000) {
    const candidate = `DGRY-${token}-${String(n).padStart(2, "0")}`;
    if (!used.has(candidate)) return candidate;
    n += 1;
  }
  return `DGRY-${token}-${String(n).padStart(2, "0")}`;
}

/**
 * Ne remplace jamais un SKU saisi manuellement ; génère seulement si le champ est vide.
 * Si le SKU auto `DGRY-XX-##` entre en collision (nouvelle fiche), incrémente au prochain libre.
 * `excludeNormalizedSku` : SKU du produit en cours d’édition (évite de rebaptiser à l’enregistrement).
 */
export function resolveProductSkuForSave(
  category: ProductCategory,
  skuInput: string,
  existingSkus: readonly string[],
  options?: { excludeNormalizedSku?: string },
): string {
  const trimmed = skuInput.trim();
  const manual = trimmed ? sanitizeSkuFieldInput(trimmed) : "";
  const base = manual
    ? isAutoGeneratedCategorySku(manual, category)
      ? normalizeSkuInput(manual)
      : manual
    : newProductSku(category, existingSkus);
  const exclude = options?.excludeNormalizedSku
    ? normalizeSkuInput(options.excludeNormalizedSku)
    : "";
  const used = new Set(
    existingSkus
      .map(normalizeSkuInput)
      .filter((sku) => sku.length > 0 && sku !== exclude),
  );
  if (isAutoGeneratedCategorySku(base, category) && used.has(base)) {
    return newProductSku(category, existingSkus);
  }
  return base;
}
