export type CategoryDefaultProfile = {
  defaultSizes: readonly string[];
  suggestedPriceLabel: string;
  /** Grammage indicatif standard (fill-empty uniquement). */
  defaultSizeGuide?: string;
  defaultPrintPlacement?: ProductPrintPlacement;
  defaultLimitedEdition?: string;
  /** Labels internes (futur affichage CRM) — non persistés en DB. */
  taxonomyTags?: readonly string[];
};

export type CatalogProductMatrix = {
  category: ProductCategory;
  price: number;
  sizes: readonly ProductSize[];
  description: string;
  materials: string;
  sizeGuide: string;
  fabrication: string;
  limitedEdition: string;
  printPlacement: ProductPrintPlacement;
};

export type SmartProductAutoTagFormState = {
  sku: string;
  name: string;
  variant: string;
  colorDeclinations: string[];
  category: ProductCategory;
  price: string;
  stock: string;
  sizes: ProductSize[];
} & ProductStoryFormFields;

export type AutoTagCtx = {
  editingId: string | null;
  existingSkus: readonly string[];
  mergeMode?: "fill-empty" | "replace";
};

/** Story d’une autre catégorie (base catalogue / collage) — à vider au changement de famille. */
export function clearStoryForCategoryChange(
  prev: SmartProductAutoTagFormState,
  isEdit: boolean,
): ProductStoryFormFields {
  if (isEdit) {
    return {
      description: "",
      fabrication: "",
      limitedEdition: "",
      materials: prev.materials,
      sizeGuide: prev.sizeGuide,
      printPlacement: prev.printPlacement,
    };
  }
  return {
    description: "",
    fabrication: "",
    limitedEdition: "",
    materials: "",
    sizeGuide: "",
    printPlacement: "",
  };
}

const EMPTY_AUTO_TAG_FORM_BASE: Omit<SmartProductAutoTagFormState, keyof ProductStoryFormFields | "category"> & {
  category?: ProductCategory;
} = {
  sku: "",
  name: "",
  variant: "",
  colorDeclinations: [],
  price: "",
  stock: "",
  sizes: [],
};

/** Nouvelle fiche CRM — passe par `applyCategoryDefaults` (tailles, SKU, stock 10, prix conseillé si vide). */
export function createNewProductFormState(
  category: ProductCategory,
  existingSkus: readonly string[],
): SmartProductAutoTagFormState {
  const blank: SmartProductAutoTagFormState = {
    ...EMPTY_AUTO_TAG_FORM_BASE,
    category,
    description: "",
    fabrication: "",
    limitedEdition: "",
    materials: "",
    sizeGuide: "",
    printPlacement: "",
  };
  return applyCategoryDefaults(blank, category, {
    editingId: null,
    existingSkus,
    mergeMode: "fill-empty",
  });
}

function profileForCategory(category: ProductCategory): CategoryDefaultProfile {
  const defaultSizes = defaultSelectedSizesForCategory(category);
  const suggestedPriceLabel = String(SUGGESTED_PRICE_EUR_BY_CATEGORY[category]);
  const base = { defaultSizes, suggestedPriceLabel } satisfies CategoryDefaultProfile;

  switch (category) {
    case "Hoodies":
      return {
        ...base,
        defaultSizeGuide: "400 g/m²",
        taxonomyTags: ["sweat", "heavyweight", "hoodie"],
      };
    case "Hoodies zippés":
      return {
        ...base,
        defaultSizeGuide: "400 g/m²",
        taxonomyTags: ["sweat", "zip", "hoodie"],
      };
    case "Crewnecks":
      return {
        ...base,
        defaultSizeGuide: "340 g/m²",
        taxonomyTags: ["sweat", "crewneck"],
      };
    case "T-shirts":
      return {
        ...base,
        defaultSizeGuide: "240 g/m²",
        taxonomyTags: ["tee", "lightweight"],
      };
    case "Jerseys":
      return {
        ...base,
        defaultSizeGuide: "180 g/m²",
        taxonomyTags: ["jersey", "sport"],
      };
    case "Pants":
      return {
        ...base,
        taxonomyTags: ["pants", "cargo"],
      };
    case "Crop tops":
      return {
        ...base,
        defaultSizeGuide: "200 g/m²",
        taxonomyTags: ["crop", "lightweight"],
      };
    case "Caps":
      return {
        ...base,
        taxonomyTags: ["caps", "accessory"],
      };
    default:
      return base;
  }
}

export const CATEGORY_DEFAULT_PROFILES: Record<ProductCategory, CategoryDefaultProfile> =
  Object.fromEntries(
    (
      [
        "Hoodies",
        "Hoodies zippés",
        "Crewnecks",
        "T-shirts",
        "Jerseys",
        "Pants",
        "Crop tops",
        "Caps",
      ] as const
    ).map((cat) => [cat, profileForCategory(cat)]),
  ) as Record<ProductCategory, CategoryDefaultProfile>;

export function categoryStandardGrammage(category: ProductCategory): string | undefined {
  return CATEGORY_DEFAULT_PROFILES[category]?.defaultSizeGuide;
}

function filterSizesForCategory(sizes: readonly ProductSize[], category: ProductCategory): ProductSize[] {
  const allowed = new Set(ADMIN_CATEGORY_SIZES[category].map((s) => String(s)));
  return sizes.filter((s) => allowed.has(String(s)));
}

function applyStoryProfile(
  prev: SmartProductAutoTagFormState,
  profile: CategoryDefaultProfile,
  mergeMode: "fill-empty" | "replace",
): SmartProductAutoTagFormState {
  const fill = mergeMode === "fill-empty";
  let next = { ...prev };
  const assign = (key: keyof ProductStoryFormFields, value: string | ProductPrintPlacement) => {
    const current = next[key];
    const empty = typeof current === "string" ? !current.trim() : !current;
    if (fill && !empty) return;
    if (typeof value === "string" && !value.trim()) return;
    next = { ...next, [key]: value };
  };
  if (profile.defaultSizeGuide) assign("sizeGuide", profile.defaultSizeGuide);
  if (profile.defaultLimitedEdition) assign("limitedEdition", profile.defaultLimitedEdition);
  if (profile.defaultPrintPlacement) assign("printPlacement", profile.defaultPrintPlacement);
  return next;
}

