/** Base catalogue mémorisée — fill-empty (ne touche pas nom, visuels, couleurs déjà choisies). */
export function applyCatalogProductMatrix(
  prev: SmartProductAutoTagFormState,
  matrix: CatalogProductMatrix,
  ctx: AutoTagCtx,
): SmartProductAutoTagFormState {
  const fill = (ctx.mergeMode ?? "fill-empty") === "fill-empty";
  let next: SmartProductAutoTagFormState = { ...prev, category: matrix.category };

  const assignStory = (key: keyof ProductStoryFormFields, value: string) => {
    if (!value.trim()) return;
    const current = String(next[key] ?? "").trim();
    if (fill && current.length > 0) return;
    next = { ...next, [key]: value.trim() };
  };

  assignStory("description", matrix.description);
  assignStory("materials", matrix.materials);
  assignStory("sizeGuide", matrix.sizeGuide);
  assignStory("fabrication", matrix.fabrication);
  assignStory("limitedEdition", matrix.limitedEdition);
  if (!fill || !next.printPlacement) {
    next.printPlacement = matrix.printPlacement;
  }

  if (!fill || !next.price.trim()) {
    next.price = String(matrix.price);
  }
  if (!fill || next.sizes.length === 0) {
    next.sizes = [...matrix.sizes];
  }
  if (!ctx.editingId && (isAutoGeneratedCategorySku(prev.sku, prev.category) || !prev.sku.trim())) {
    next.sku = newProductSku(matrix.category, ctx.existingSkus);
  }

  next = applyStoryProfile(next, CATEGORY_DEFAULT_PROFILES[matrix.category], ctx.mergeMode ?? "fill-empty");
  return next;
}

export function applyCategoryDefaults(
  prev: SmartProductAutoTagFormState,
  nextCategory: ProductCategory,
  ctx: AutoTagCtx,
): SmartProductAutoTagFormState {
  const profile = CATEGORY_DEFAULT_PROFILES[nextCategory];
  const mergeMode = ctx.mergeMode ?? "fill-empty";
  const isEdit = Boolean(ctx.editingId);
  const categoryChanged = prev.category !== nextCategory;
  const nowPants = isPantsCategory(nextCategory);
  const wasPants = isPantsCategory(prev.category);

  const nextSizes = isEdit
    ? filterSizesForCategory(prev.sizes, nextCategory)
    : (profile.defaultSizes as ProductSize[]);

  const storyBase = categoryChanged ? { ...prev, ...clearStoryForCategoryChange(prev, isEdit) } : prev;

  let next: SmartProductAutoTagFormState = {
    ...storyBase,
    category: nextCategory,
    sizes: nextSizes,
  };

  if (!isEdit) {
    const nextSku =
      isAutoGeneratedCategorySku(prev.sku, prev.category) || !prev.sku.trim()
        ? newProductSku(nextCategory, ctx.existingSkus)
        : normalizeSkuInput(prev.sku);
    next.sku = nextSku;
    if (!prev.stock.trim()) {
      next.stock = String(DEFAULT_SHOP_PRODUCT_STOCK);
    }
    if (!prev.price.trim()) {
      next.price = profile.suggestedPriceLabel;
    }
    next = applyStoryProfile(next, profile, mergeMode);

    if (nowPants) {
      const w = normalizePantWaistSize(prev.variant.trim());
      const variant = w && nextSizes.includes(w) ? w : "";
      return applyStoryProfile(
        {
          ...next,
          variant,
          colorDeclinations: [],
        },
        profile,
        mergeMode,
      );
    }

    const preservedColors = wasPants ? [] : [...prev.colorDeclinations];
    let preservedVariant =
      wasPants || isValidPantWaistSize(prev.variant) ? "" : prev.variant.trim();
    if (
      preservedColors.length > 0 &&
      preservedVariant &&
      !preservedColors.some(
        (c) => c.trim().toUpperCase() === preservedVariant.toUpperCase(),
      )
    ) {
      preservedVariant = preservedColors[0] ?? preservedVariant;
    } else if (!preservedVariant && preservedColors.length > 0) {
      preservedVariant = preservedColors[0] ?? "";
    }

    return applyStoryProfile(
      {
        ...next,
        variant: preservedVariant,
        colorDeclinations: preservedColors,
      },
      profile,
      mergeMode,
    );
  }

  if (nowPants) {
    const w = normalizePantWaistSize(prev.variant.trim());
    const variant = w && nextSizes.includes(w) ? w : "";
    return applyStoryProfile(
      {
        ...next,
        variant,
        colorDeclinations: [],
      },
      profile,
      mergeMode,
    );
  }

  let nextVariant = prev.variant.trim();
  const nextColors = [...prev.colorDeclinations];

  if (wasPants || isValidPantWaistSize(nextVariant)) {
    nextVariant = "";
  } else if (
    nextColors.length > 0 &&
    nextVariant &&
    !nextColors.some((c) => c.trim().toUpperCase() === nextVariant.toUpperCase())
  ) {
    nextVariant = "";
  }

  return applyStoryProfile(
    {
      ...next,
      variant: nextVariant,
      colorDeclinations: nextColors,
    },
    profile,
    mergeMode,
  );
}

export function patchFormFromSmartParse(
  prev: SmartProductAutoTagFormState,
  parsed: SmartProductParseOutput,
  mergeMode: "fill-empty" | "replace" = "fill-empty",
): SmartProductAutoTagFormState {
  const fill = mergeMode === "fill-empty";
  const forced = new Set(parsed.filled);
  let next = { ...prev };
  if (parsed.detectedCategory !== undefined) {
    next.category = parsed.detectedCategory;
  }
  const assign = (
    key: keyof SmartProductAutoTagFormState,
    value: string | undefined,
    parseKey?: SmartProductParseOutput["filled"][number],
  ) => {
    if (value === undefined || !value.trim()) return;
    const incoming = value.trim();
    const currentRaw = String(next[key] ?? "");
    if (storyFieldsSemanticallyEqual(incoming, currentRaw)) return;
    const detectedByCollage = parseKey !== undefined && forced.has(parseKey);
    if (fill && currentRaw.trim().length > 0 && !detectedByCollage) return;
    next = { ...next, [key]: incoming };
  };
  if (parsed.sku?.trim()) {
    const skuIncoming = normalizeSkuInput(parsed.sku);
    if (!storyFieldsSemanticallyEqual(skuIncoming, next.sku)) {
      next = { ...next, sku: skuIncoming };
    }
  }
  assign("name", parsed.name, "name");
  assign("description", parsed.description, "description");
  assign("materials", parsed.materials, "materials");
  if (parsed.weight?.trim()) {
    const w = parsed.weight.trim();
    if (!storyFieldsSemanticallyEqual(w, next.sizeGuide)) {
      next = { ...next, sizeGuide: w };
    }
  } else {
    assign("sizeGuide", parsed.weight);
  }
  assign("fabrication", parsed.fabrication, "fabrication");
  assign("limitedEdition", parsed.limitedEdition, "limitedEdition");
  if (parsed.printPlacement && (!fill || !next.printPlacement)) {
    next.printPlacement = parsed.printPlacement;
  }
  assign("price", parsed.price, "price");
  assign("stock", parsed.stock, "stock");
  return next;
}

export function applyParsedProductDefaults(
  prev: SmartProductAutoTagFormState,
  parsed: SmartProductParseOutput,
  ctx: AutoTagCtx & { familySuggestedPriceLabel?: string; familyCategory?: ProductCategory },
): SmartProductAutoTagFormState {
  const filledSet = new Set(parsed.filled);
  const effectiveDetected = parsed.detectedCategory ?? ctx.familyCategory;
  const targetCategory = effectiveDetected ?? prev.category;
  const categoryChanged =
    effectiveDetected !== undefined && effectiveDetected !== prev.category;

  const wasPantsBefore = isPantsCategory(prev.category);
  const pantsTarget = isPantsCategory(targetCategory);

  let storyCleared = prev;
  if (categoryChanged) {
    storyCleared = { ...prev, ...clearStoryForCategoryChange(prev, Boolean(ctx.editingId)) };
  }

  let prep: SmartProductAutoTagFormState =
    categoryChanged && !ctx.editingId && !filledSet.has("variant")
      ? {
          ...storyCleared,
          category: targetCategory,
          sizes: filledSet.has("sizes") ? prev.sizes : [],
          variant:
            pantsTarget || wasPantsBefore || isValidPantWaistSize(prev.variant) ? "" : prev.variant,
          colorDeclinations: pantsTarget ? [] : wasPantsBefore ? [] : [...prev.colorDeclinations],
        }
      : categoryChanged
        ? {
            ...storyCleared,
            category: targetCategory,
            sizes: filledSet.has("sizes") ? prev.sizes : prev.sizes,
          }
        : { ...storyCleared };

  if (categoryChanged && !filledSet.has("sizes") && !ctx.editingId) {
    prep = {
      ...prep,
      sizes: CATEGORY_DEFAULT_PROFILES[targetCategory].defaultSizes as ProductSize[],
      ...(prev.stock.trim() ? {} : { stock: String(DEFAULT_SHOP_PRODUCT_STOCK) }),
    };
  }

  const mergeMode = ctx.mergeMode ?? "fill-empty";
  let next = patchFormFromSmartParse(prep, parsed, mergeMode);
  if (!parsed.detectedCategory && ctx.familyCategory) {
    next.category = ctx.familyCategory;
  }

  if (!parsed.price && ctx.familySuggestedPriceLabel && !prev.price.trim()) {
    next.price = ctx.familySuggestedPriceLabel;
  }

  const pantsNow = isPantsCategory(targetCategory);

  if (pantsNow && filledSet.has("sizes") && parsed.sizes !== undefined && parsed.sizes.length > 0) {
    next.sizes = parsed.sizes;
    if (!parsed.sizes.includes(next.variant)) {
      next.variant = parsed.sizes[0] ?? next.variant;
    }
  } else if (!pantsNow && filledSet.has("variant") && parsed.variantColor !== undefined) {
    next.variant = parsed.variantColor;
    next.colorDeclinations = [parsed.variantColor];
  }

  if (!pantsNow && filledSet.has("sizes") && parsed.sizes !== undefined && parsed.sizes.length > 0) {
    next.sizes = parsed.sizes;
  }

  if (!next.stock.trim()) {
    next.stock = String(DEFAULT_SHOP_PRODUCT_STOCK);
  }

  next = applyStoryProfile(next, CATEGORY_DEFAULT_PROFILES[targetCategory], mergeMode);

  return next;
}

/** Recap Smart collage : libellé FR + code court (BLK, WHT…). */
export function displaySemanticBlocksForCrm(blocks: readonly MakerSemanticBlock[]): MakerSemanticBlock[] {
  return blocks.map((b) =>
    b.key === "color"
      ? {
          ...b,
          value: `${frenchLabelForColorPreset(b.value)} (${techCodeForColorPreset(b.value)})`,
        }
      : b,
  );
}
