  function removeColorDeclination(color: string) {
    const canon = canonicalColorDeclinationValue(color);
    if (!canon) return;
    setForm((previous) => {
      const nextDecl = previous.colorDeclinations.filter(
        (item) => !colorDeclinationsCanonicallyEqual(item, canon),
      );
      setColorListDraft(colorDeclinationsLabel(nextDecl));
      const nextVariant = colorDeclinationsCanonicallyEqual(previous.variant, canon)
        ? ""
        : previous.variant;
      return { ...previous, colorDeclinations: nextDecl, variant: nextVariant };
    });
  }

  function addColorDeclination(color: string) {
    const canon = canonicalColorDeclinationValue(color);
    if (!canon) return;
    setForm((previous) => {
      if (previous.colorDeclinations.some((c) => colorDeclinationsCanonicallyEqual(c, canon))) {
        return previous;
      }
      const next = [...previous.colorDeclinations, canon];
      setColorListDraft(colorDeclinationsLabel(next));
      const nextVariant = previous.variant.trim() ? previous.variant : canon;
      return { ...previous, colorDeclinations: next, variant: nextVariant };
    });
  }

