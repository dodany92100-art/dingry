function SmartCollageSkeletonMarkers({ text }: { text: string }) {
  const chunks = text.split(/([:@#])/g);
  return (
    <>
      {chunks.map((chunk, index) =>
        chunk === ":" || chunk === "@" || chunk === "#" ? (
          <span key={`mk-${index}`} className="font-bold text-white">
            {chunk}
          </span>
        ) : (
          <span key={`txt-${index}`}>{chunk}</span>
        ),
      )}
    </>
  );
}

